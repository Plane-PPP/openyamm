#!/usr/bin/env python3
"""Regenerate the approved v0.4 registry and probabilities; never edits runtime assets or balance tables."""
from pathlib import Path
import csv

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'docs/research'


def write(name, rows):
    with (OUT / name).open('w', newline='', encoding='utf-8') as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]), lineterminator='\n')
        writer.writeheader()
        writer.writerows(rows)


registry = list(csv.DictReader((OUT / 'lethal-strike-classification.csv').open()))
ids = [int(row['monster_id']) for row in registry]
assert ids == list(range(1, 653)) + list(range(901, 907))
assert all(row['category'] in ('NORMAL', 'GIANT') for row in registry)
lookup = {int(row['monster_id']): row for row in registry}
for first in (28, 31, 58, 61, 76, 79, 91, 106):
    assert all(lookup[mid]['category'] == 'NORMAL' for mid in range(first, first + 3))
for first in (130, 220):
    assert all(lookup[mid]['category'] == 'GIANT' for mid in range(first, first + 3))
giant_ids = [row['monster_id'] for row in registry if row['category'] == 'GIANT']
header = '''#pragma once

#include <algorithm>
#include <array>
#include <cstdint>

namespace OpenYAMM::Game
{
// Approved v0.4 registry, source: docs/research/lethal-strike-classification.csv.
// Generated by tools/generate_lethal_strike_research.py; do not edit by hand.
// These are merged template IDs, never actor indices or translated names.
inline bool lethalStrikeKnownMonster(uint32_t id)
{
    return (id >= 1 && id <= 652) || (id >= 901 && id <= 906);
}

inline bool lethalStrikeGiantMonster(uint32_t id)
{
    constexpr std::array<uint32_t, COUNT> GiantIds = {
IDS
    };
    return std::binary_search(GiantIds.begin(), GiantIds.end(), id);
}
}
'''.replace('COUNT', str(len(giant_ids))).replace('IDS', '\n'.join(
    '        ' + ', '.join(giant_ids[i:i+15]) + ',' for i in range(0, len(giant_ids), 15)))
(ROOT / 'game/gameplay/LethalStrikeMonsters.h').write_text(header)
stats = list(csv.DictReader((OUT / 'monster-stats.csv').open()))
for row in stats:
    entry = lookup[int(row['monster_id'])]
    assert row['picture'] == entry['picture'] and row['family'] == entry['family']
    row['category_proposed'] = entry['category']
    row['category_review'] = 'approved-v0.4'
    row['classification_basis'] = 'approved Lethal Strike v0.4 registry; explicit template ID'
write('monster-stats.csv', stats)
result = []
for rank, a, b in [('Normal', .60, 0), ('Expert', .90, .56), ('Master', 1.10, .64), ('Grandmaster', 1.30, .72)]:
    for s in (1, 5, 10, 15, 20):
        for v in (0, 1, 5, 10, 15, 20):
            for pl, ml in [(100, 100-d) for d in (-60, -40, -20, 0, 20, 24, 60)] + [(50, m) for m in (30, 50, 70, 90, 110)]:
                delta = pl - ml
                kl = min(1.4, 1 + delta / 60) if delta >= 0 else 30 / (30 + 1.5 * abs(delta))
                p0 = a*s + b*v
                for category, hp in [('NORMAL', 100), ('GIANT', 61), ('GIANT', 60), ('GIANT', 59)]:
                    kg = int(category == 'NORMAL' or 5*hp < 3*100)
                    result.append(dict(version='0.4',S=s,V=v,mastery=rank,player_level=pl,monster_level=ml,
                                       category=category,current_hp=hp,max_hp=100,P0_percent=p0,KL=kl,KG=kg,
                                       P_percent=min(30, p0*kl*kg)))
write('lethal-strike-probabilities-v0.4.csv', result)
print(f'Approved: {len(ids)} templates, {len(giant_ids)} GIANT, {len(result)} probability scenarios')
